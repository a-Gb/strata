//! License-safe golden sources for projection and visual-regression tests.

#[cfg(test)]
use strata_core::{DomainError, SourceGeneration, SourceId};
#[cfg(test)]
use strata_source::{ByteSource, RetainedByteSource};

/// Ground-truth content class represented by a projection fixture.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProjectionFixtureKind {
    /// Printable, line-oriented text.
    Text,
    /// Generated instruction-like bytes with repeated prologue and return patterns.
    ExecutableCode,
    /// A valid zlib stream generated from synthetic source bytes.
    Compressed,
    /// A generated planar grayscale image without a container header.
    Image,
    /// Repeated fixed-width little-endian records.
    AlignedRecords,
    /// Aligned little-endian values that point into one declared address range.
    Pointers,
    /// Exact repeated blocks separated by small record identifiers.
    RepeatedBlocks,
}

/// One deterministic, distributable projection fixture and its acceptance metadata.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProjectionGoldenFixture {
    /// Stable fixture identifier.
    pub id: &'static str,
    /// Deliberately generated content class.
    pub kind: ProjectionFixtureKind,
    /// Synthetic immutable bytes.
    pub bytes: Vec<u8>,
    /// SPDX-compatible license statement for the generated bytes.
    pub license: &'static str,
    /// Whether the bytes may be committed and redistributed with the repository.
    pub distributable: bool,
    /// Observable properties that projection tests may claim as ground truth.
    pub expected_properties: &'static [&'static str],
    /// Canonical SHA-256 of [`Self::bytes`].
    pub sha256: &'static str,
}

