fn image_bytes() -> Vec<u8> {
    let mut bytes = Vec::with_capacity(32 * 16);
    for y in 0_u8..16 {
        for x in 0_u8..32 {
            bytes.push(x.wrapping_mul(8) ^ y.wrapping_mul(17));
        }
    }
    bytes
}

fn aligned_record_bytes() -> Vec<u8> {
    let mut bytes = Vec::with_capacity(64 * 16);
    for record in 0_u32..64 {
        bytes.extend_from_slice(&record.to_le_bytes());
        bytes.extend_from_slice(&(record.saturating_mul(64)).to_le_bytes());
        bytes.extend_from_slice(&(0x4000_u32 | record).to_le_bytes());
        bytes.extend_from_slice(&record.rotate_left(7).to_le_bytes());
    }
    bytes
}

fn pointer_bytes() -> Vec<u8> {
    let mut bytes = Vec::with_capacity(64 * 8);
    for index in 0_u64..64 {
        let target = 0x1000_u64 + ((index * 32) % 0x800);
        bytes.extend_from_slice(&target.to_le_bytes());
    }
    bytes
}

fn repeated_bytes() -> Vec<u8> {
    let mut bytes = Vec::with_capacity(16 * 32);
    for index in 0_u8..16 {
        bytes.extend_from_slice(b"STRATA-REPEAT-GOLDEN-BLOCK-");
        bytes.extend_from_slice(&[index, index ^ 0xff, 0x00, 0xff, 0x7e]);
    }
    bytes
}

#[cfg(test)]
fn fixture_digest(bytes: &[u8]) -> Result<String, DomainError> {
    let source = RetainedByteSource::new(
        SourceId(1),
        SourceGeneration(0),
        "projection-golden",
        bytes.to_vec().into(),
    )?;
    source
        .descriptor()
        .content_digest
        .ok_or_else(|| DomainError::Internal("retained fixture digest was not sealed".to_owned()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixture_metadata_and_digests_are_complete() -> Result<(), DomainError> {
        let fixtures = projection_golden_fixtures();
        assert_eq!(fixtures.len(), 7);
        for fixture in fixtures {
            assert_eq!(fixture_digest(&fixture.bytes)?, fixture.sha256);
            assert!(fixture.distributable);
            assert!(!fixture.bytes.is_empty());
            assert!(!fixture.expected_properties.is_empty());
        }
        Ok(())
    }
}
