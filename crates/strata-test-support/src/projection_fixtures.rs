const fn fixture(
    id: &'static str,
    kind: ProjectionFixtureKind,
    bytes: Vec<u8>,
    expected_properties: &'static [&'static str],
    sha256: &'static str,
) -> ProjectionGoldenFixture {
    ProjectionGoldenFixture {
        id,
        kind,
        bytes,
        license: "CC0-1.0 (synthetic)",
        distributable: true,
        expected_properties,
        sha256,
    }
}

fn text_bytes() -> Vec<u8> {
    let line = b"STRATA projection golden: text, fields, offsets, evidence.\n";
    line.iter().copied().cycle().take(512).collect()
}

